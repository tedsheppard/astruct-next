import { chromium } from 'playwright'
const br = await chromium.launch({ headless: true })
const page = await br.newContext({ viewport: { width: 1440, height: 900 } }).then(c => c.newPage())
const stamp = Date.now()
const email = `qa+billing-${stamp}@gmail.com`
console.log('email:', email)
await page.goto('https://app.astruct.io/register', { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(2500)
await page.locator('input[placeholder="Your name"]').fill('Billing Test')
await page.locator('input[placeholder="you@company.com"]').fill(email)
await page.locator('input[type="password"]').fill('AbcDef123!')
await page.locator('button:has-text("Create account")').click()
await page.waitForTimeout(8000)
console.log('after register URL:', page.url())
await page.goto('https://app.astruct.io/settings/billing', { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(15000)
console.log('billing URL:', page.url())
await page.screenshot({ path: 'test-results/full-coverage/screenshots/409_verify_c5_billing-rerun.png', fullPage: true })
const planCount = await page.locator('text=Pro Contract').count()
const stepper = await page.locator('button[aria-label="Increase quantity"]').count()
const upgradeBtn = await page.locator('button:has-text("Upgrade to Pro")').count()
const aiUsage = await page.locator('text=AI usage this cycle').count()
console.log(`Pro Contract text: ${planCount}, stepper: ${stepper}, Upgrade button: ${upgradeBtn}, "AI usage this cycle": ${aiUsage}`)
await br.close()
